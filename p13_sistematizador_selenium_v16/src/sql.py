SQL_PREGUNTAS = '''
SELECT ID_PREGUNTA, PREGUNTA_CODIGO, PREGUNTA_DESCRIPCION, PREGUNTA_SITUACION_DESEADA
FROM dbo.VW_PREGUNTA_POR_EVALUACION
WHERE EvaluacionId = ?
ORDER BY PREGUNTA_CODIGO;
'''

SQL_APLICACION = '''
SELECT TOP (1) Id
FROM dbo.Aplicacion
WHERE EvaluacionId = ? AND InformanteId = ?
ORDER BY Id DESC;
'''
